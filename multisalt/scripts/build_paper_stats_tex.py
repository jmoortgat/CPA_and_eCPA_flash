#!/usr/bin/env python3
"""Consolidate every per-figure stats JSON into a single LaTeX macro file.

Reads ``results_cache/<name>_stats.json`` (written by each ``fig_*.py``)
and writes two LaTeX files under ``paper_tables/`` (or ``$ECPA_PAPER_DIR``):

  paper_stats.tex           \newcommand definitions for the numbers cited
                            in the text of Paper II (AAREs, N counts, best
                            salt, range macros).
  tables/aare_per_salt.tex  per-salt AARE table (a summary of the per-salt
                            numbers in the text; not a published table).

Design principle: every number that used to be hand-typed in the TeX
becomes a \newcommand, so a refit runs `make paper` and the paper's
narrative and Table 6 update automatically. The old hand-typed literals
are replaced by \aareXxx macros in a corresponding TeX edit.

Usage:
    python3 scripts/build_paper_stats_tex.py

Run this after `scripts/make_all_paper_figures.py`, or via the top-level
Makefile: `make paper`.
"""
from __future__ import annotations

import os
import sys
from datetime import datetime, timezone
from pathlib import Path

_CODE = Path(__file__).resolve().parents[1]
sys.path.insert(0, str(_CODE / "scripts"))
from data_loader import load_stats  # noqa: E402

# Output folder: $ECPA_PAPER_DIR, else <package>/paper_tables.
_PAPER = Path(os.environ.get("ECPA_PAPER_DIR", _CODE / "paper_tables"))
_PAPER.mkdir(parents=True, exist_ok=True)
_OUT_STATS = _PAPER / "paper_stats.tex"
_OUT_TABLE = _PAPER / "tables" / "aare_per_salt.tex"

# LaTeX-safe salt label -> macro suffix (table row order).
_SALT_ORDER = ("NaCl", "KCl", "CaCl", "MgCl", "NaSO")
_SALT_TEX = {
    "NaCl": r"\ce{NaCl}",
    "KCl":  r"\ce{KCl}",
    "CaCl": r"\ce{CaCl2}",
    "MgCl": r"\ce{MgCl2}",
    "NaSO": r"\ce{Na2SO4}",
}
_SALT_MACRO = {
    "NaCl": "NaCl", "KCl": "KCl",
    "CaCl": "CaCl", "MgCl": "MgCl", "NaSO": "NaSO",
}


def _fmt(x, spec: str = ".2f") -> str:
    """Format a scalar for LaTeX; fall back to `---` for missing/NaN."""
    if x is None:
        return "---"
    try:
        f = float(x)
    except (TypeError, ValueError):
        return str(x)
    if f != f:  # NaN
        return "---"
    return format(f, spec)


def _new(name: str, value) -> str:
    """One \newcommand line. Emits an int without decimals when the value
    is an int (or a float that happens to be integer-valued, so that
    N counts don't render as ``137.00``)."""
    if isinstance(value, str):
        return rf"\newcommand{{\{name}}}{{{value}}}"
    if value is None:
        return rf"\newcommand{{\{name}}}{{---}}"
    if isinstance(value, bool):
        return rf"\newcommand{{\{name}}}{{{value}}}"
    if isinstance(value, int):
        return rf"\newcommand{{\{name}}}{{{value}}}"
    try:
        f = float(value)
    except (TypeError, ValueError):
        return rf"\newcommand{{\{name}}}{{{value}}}"
    if f != f:  # NaN
        return rf"\newcommand{{\{name}}}{{---}}"
    if f.is_integer():
        return rf"\newcommand{{\{name}}}{{{int(f)}}}"
    return rf"\newcommand{{\{name}}}{{{_fmt(f)}}}"


def main() -> int:
    fp = load_stats("fig_flash_predictions")   # § 3.7 headline + Table 6
    co2 = load_stats("fig_co2_singlesalt")     # § 3.4 per-salt narrative
    ch4 = load_stats("fig_ch4_singlesalt")     # § 3.5 CH4 narrative
    bt = load_stats("build_paper_tables")      # Susak full-T AAD (§ 3.5)
    coll = load_stats("fig_colligative")       # § 3.2 osmotic coefficients
    ag = load_stats("fig_additional_gases")    # § 3.6 additional gases N2+H2

    if not (fp or co2 or ch4 or bt or coll or ag):
        print("WARNING: no stats JSON files found in results_cache/. "
              "Run `python3 scripts/make_all_paper_figures.py` first.")

    lines: list[str] = []
    lines.append(
        "% AUTO-GENERATED by scripts/build_paper_stats_tex.py "
        f"({datetime.now(timezone.utc).isoformat(timespec='seconds')})."
    )
    lines.append("% DO NOT EDIT BY HAND. Re-run `make paper` after refitting.")
    lines.append("% Every macro below reflects the current state of "
                 "results_cache/*_stats.json.")
    lines.append("")

    # ---- § 3.7 CO2 flash headline (Section 3.7 + Table 6) --------------
    if fp:
        lines.append("% --- Section 3.7 CO2 flash headline (fig_flash_predictions) ---")
        lines.append("% All authors pooled; N_teymouri kept for the")
        lines.append("% beyond-calibration-pressure sentence.")
        lines.append(_new("aareCOtwoOverall",         fp.get("aare_overall")))
        lines.append(_new("NflashTotal",              fp.get("N_total")))
        lines.append(_new("NflashTeymouri",           fp.get("N_teymouri")))
        lines.append(_new("bestSaltName",             _SALT_TEX.get(
            fp.get("best_salt", ""), fp.get("best_salt", "?"))))
        lines.append(_new("bestSaltAare",             fp.get("best_salt_aare")))
        # Per-salt macros (used in narrative when specific numbers are cited)
        for salt, entry in fp.get("per_salt", {}).items():
            suf = _SALT_MACRO.get(salt, salt)
            lines.append(_new(f"aareCOtwo{suf}", entry.get("aare")))
            lines.append(_new(f"NCOtwo{suf}",    entry.get("N")))
        lines.append("")

    # ---- § 3.4 CO2 single-salt calibration narrative ------------------
    if co2:
        lines.append("% --- Section 3.4 CO2 single-salt AAD (fig_co2_singlesalt) ---")
        # Range across salts feeds the abstract "5--13\%" statement.
        # Abstract-only range macros: 1 decimal place (coarser than the
        # per-salt narrative numbers below, which keep 2 d.p.).
        lines.append(_new("aareCOtwoRangeLow",  _fmt(co2.get("range_low"),  ".1f")))
        lines.append(_new("aareCOtwoRangeHigh", _fmt(co2.get("range_high"), ".1f")))
        for salt, entry in co2.get("per_salt", {}).items():
            suf = _SALT_MACRO.get(salt, salt)
            lines.append(_new(f"aadCOtwoSingle{suf}", entry.get("aad")))
            lines.append(_new(f"NCOtwoSingle{suf}",   entry.get("N")))
        lines.append("")

    # ---- § 3.5 CH4 single-salt narrative -------------------------------
    if ch4:
        lines.append("% --- Section 3.5 CH4 single-salt AARE (fig_ch4_singlesalt) ---")
        lines.append(_new("aareCHfourOverall",        ch4.get("aare_overall")))
        lines.append(_new("NCHfourTotal",             ch4.get("N_total")))
        # Prefer the full-T Susak number from build_paper_tables (which uses
        # stability_flash to cover 548/573/598 K); fall back to the
        # fig_ch4_singlesalt heuristic if the build_paper_tables sidecar
        # is missing.
        susak_full = (bt or {}).get("susak_nacl_full_T_aad")
        lines.append(_new(
            "aareCHfourSusakNaClHiT",
            susak_full if susak_full is not None
            else ch4.get("susak_nacl_high_T_aare"),
        ))
        # Also expose Susak's full-T temperature bracket for the paper
        # narrative -- lets §3.5 say "up to 598 K" via a macro so the
        # value updates when the underlying data does.
        lines.append(_new("TsusakNaClHiT",
                          (bt or {}).get("susak_nacl_full_T_Tmax")))
        lines.append(_new("NsusakNaClHiT",
                          (bt or {}).get("susak_nacl_full_T_N")))
        lines.append(_new("aareCHfourSmallRangeLow",  ch4.get("small_salt_range_low")))
        lines.append(_new("aareCHfourSmallRangeHigh", ch4.get("small_salt_range_high")))
        # Abstract "5--8\%" bracket: min / max across per-salt totals.
        # 1 decimal place, matching the CO2 abstract-range macros above.
        per_salt = ch4.get("per_salt", {})
        if per_salt:
            aares = [v["aare"] for v in per_salt.values()]
            lines.append(_new("aareCHfourRangeLow",  _fmt(min(aares), ".1f")))
            lines.append(_new("aareCHfourRangeHigh", _fmt(max(aares), ".1f")))
        lines.append("")

    # ---- § 3.2 osmotic coefficients of the gas-free brines --------------
    if coll:
        lines.append("% --- Section 3.2 osmotic coefficients (fig_colligative) ---")
        lines.append("% RAD of phi_osm vs Pitzer (Pitzer & Mayorga 1973 constants)")
        lines.append("% at 298.15 K; 'Fit' = within the Schlaikjer 2018 fit range.")
        for salt, entry in coll.get("per_salt", {}).items():
            suf = _SALT_MACRO.get(salt, salt)
            lines.append(_new(f"radColl{suf}", entry.get("rad_fit")))
            lines.append(_new(f"radColl{suf}Full", entry.get("rad_full")))
        pr = coll.get("cacl2_printed_row", {})
        lines.append(_new("radCollCaClPrinted", pr.get("rad_fit")))
        lines.append(_new("radCollCaClPrintedFull", pr.get("rad_full")))
        # Spot deviations of the printed Ca2+ row (signed %, 1 decimal,
        # emitted as pre-formatted strings by fig_colligative.py).
        lines.append(_new("collCaPrintedDevHalfM", pr.get("dev_pct_m0p5")))
        lines.append(_new("collCaPrintedDevOneM", pr.get("dev_pct_m1")))
        lines.append(_new("collCaPrintedDevTwoM", pr.get("dev_pct_m2")))
        lines.append(_new("collPhiDHNaCl", coll.get("phi_dh_nacl")))
        lines.append("")

    # ---- § 3.6 additional gases: N2 + H2 (fig_additional_gases) ---------
    if ag:
        lines.append("% --- Section 3.6 additional gases N2 + H2 "
                     "(fig_additional_gases) ---")
        lines.append("% N2: kij fitted to salt-free O'Sullivan 1970 data; "
                     "(Na,Cl) energies Tc-rescaled CH4 transfer.")
        n2 = ag.get("n2", {})
        lines.append(_new("aareNtwoWater",        n2.get("aare_water")))
        lines.append(_new("NNtwoWater",           n2.get("N_water")))
        lines.append(_new("aareNtwoBrine",        n2.get("aare_brine_transfer")))
        lines.append(_new("aareNtwoBrineOneM",    n2.get("aare_brine_1m")))
        lines.append(_new("aareNtwoBrineFourM",   n2.get("aare_brine_4m")))
        lines.append(_new("NNtwoBrine",           n2.get("N_brine")))
        lines.append(_new("aareNtwoBrineFitted",  n2.get("aare_brine_fitted")))
        lines.append(_new("sNtwoFit",             n2.get("s_fit")))
        lines.append("% H2: Coelho 2025 parameterization verbatim (zero "
                     "fitting); water AARE on his fit set.")
        h2 = ag.get("h2", {})
        lines.append(_new("aareHtwoWater",        h2.get("aare_water_fitset")))
        lines.append(_new("NHtwoWater",           h2.get("N_water_fitset")))
        lines.append(_new("aareHtwoWaterCoelho",  h2.get("aare_water_coelho")))
        lines.append(_new("aareHtwoBrine",        h2.get("aare_brine")))
        lines.append(_new("NHtwoBrine",           h2.get("N_brine")))
        lines.append(_new("aareHtwoBrineCoelho",  h2.get("aare_brine_coelho")))
        lines.append(_new("HtwoTernaryDevLow",    h2.get("ternary_dev_low")))
        lines.append(_new("HtwoTernaryDevHigh",   h2.get("ternary_dev_high")))
        lines.append("")

    _OUT_STATS.write_text("\n".join(lines) + "\n")
    print(f"  wrote {_OUT_STATS} "
          f"({sum(1 for L in lines if L.startswith(chr(92)+'newcommand'))} macros)")

    # ---- Table 6 body: tables/aare_per_salt.tex ------------------------
    # The file is a COMPLETE \begin{tabular}...\end{tabular} block.
    # the paper source includes the \begin{table}/\caption/\label wrapper and
    # `\input`s this file OUTSIDE the tabular scope, which avoids the
    # "\input inside tabular breaks alignment" LaTeX quirk.
    if fp and fp.get("per_salt"):
        _OUT_TABLE.parent.mkdir(parents=True, exist_ok=True)
        tbl: list[str] = []
        tbl.append("% AUTO-GENERATED by scripts/build_paper_stats_tex.py.")
        tbl.append("% Refit -> `make paper` -> this file updates automatically.")
        tbl.append(r"\begin{tabular}{lcr}")
        tbl.append(r"\toprule")
        tbl.append(r"Salt & $N$ & AARE (\%) \\")
        tbl.append(r"\midrule")
        for salt in _SALT_ORDER:
            entry = fp["per_salt"].get(salt)
            if not entry:
                continue
            row = (f"{_SALT_TEX[salt]:<12s} & "
                   f"{entry['N']:>3d} & "
                   f"{_fmt(entry['aare']):>5s} \\\\")
            if salt == fp.get("best_salt"):
                row = row.replace(f"{_fmt(entry['aare']):>5s}",
                                  rf"\textbf{{{_fmt(entry['aare'])}}}",
                                  1)
            tbl.append(row)
        tbl.append(r"\midrule")
        tbl.append(
            rf"\textbf{{Total}} & \textbf{{{fp['N_total']}}} & "
            rf"\textbf{{{_fmt(fp['aare_overall'])}}} \\"
        )
        tbl.append(r"\bottomrule")
        tbl.append(r"\end{tabular}")
        _OUT_TABLE.write_text("\n".join(tbl) + "\n")
        print(f"  wrote {_OUT_TABLE} "
              f"({len(_SALT_ORDER)} salt rows + total)")

    return 0


if __name__ == "__main__":
    raise SystemExit(main())
