#!/usr/bin/env python3
"""Generate the Fortran .par parameter files FROM the Python reference.

Runs the ms_ecpa library (read-only; PYTHONPATH import) and dumps every
quantity the Fortran kernels read, at full repr precision (shortest
round-trip decimal -> bit-exact float64 on re-read), for two
configurations:

  paperII_III.par : pristine library defaults (Papers II/III multi-salt
                    production parameterization).
  paper1.par      : ms_ecpa.paper1_config applied (Paper-I ternary
                    CO2-H2O-NaCl; quadratic CO2-ion DU form on the
                    Na+/Cl- slots via U3i_form).  Scope: z_CH4 = 0,
                    NaCl only.

Parameters owned by an extension layer (ms_ecpa.extensions) are not
written here; that layer appends its own lines.

Usage:  PYTHONPATH=<code dir> python3 gen_params.py [outdir]
"""
import json
import sys
from pathlib import Path

import numpy as np

HERE = Path(__file__).resolve().parent
CODE = HERE.parents[1]
sys.path.insert(0, str(CODE))

import ms_ecpa.parameters as P          # noqa: E402
from ms_ecpa import paper1_config       # noqa: E402

SCALARS = [
    "R", "Na", "kb", "e", "eps0", "Mw", "Mh", "Mc",
    "Tc1", "Pc1", "Tc2", "Pc2", "Tc3", "Pc3",
    "b1", "c11", "a01", "b2", "c12", "a02", "w2", "b3", "c13", "a03",
    "epsW", "kappaW", "dip01", "pol1", "pol2", "pol3", "zww", "Tref",
    "Ak12", "Bk12", "Ck12", "Ak13", "Bk13", "Ck13",
    "AS13", "BS13", "CS13", "k23", "S12A",
]
FLAGS: list = []
ION_ARRAYS = ["Sgi", "bi", "Rbi", "a0i", "c1i", "Uref1i",
              "Talfa1i", "alfa1i", "Zi", "poli", "MMi",
              "A_U2i", "B_U2i", "A_Peni", "B_Peni"]


def collect():
    """Snapshot the CURRENT ms_ecpa.parameters state into a flat dict."""
    d = {}
    for k in SCALARS:
        d[k] = [float(getattr(P, k))]
    # GAMMA1/THETA1 enter the kernels only through their cosines; store
    # the exact double the Python kernels use.
    d["cosGAMMA1"] = [float(np.cos(P.GAMMA1))]
    d["cosTHETA1"] = [float(np.cos(P.THETA1))]
    for k in FLAGS:
        d[k] = [1.0 if getattr(P, k) else 0.0]
    for k in ION_ARRAYS:
        d[k] = [float(v) for v in np.asarray(getattr(P, k), dtype=float)]

    # CH4-ion DU: always the linear form in every configuration so far.
    d["U2i_form"] = [0.0] * 6
    d["U2i_quad_Uref"] = [0.0] * 6
    d["U2i_quad_Talfa"] = [1.0] * 6
    d["U2i_quad_alfa"] = [0.0] * 6

    # CO2-ion DU: linear arrays, or the Paper-I quadratic shim.
    A3 = P.A_U3i
    B3 = P.B_U3i
    if isinstance(A3, np.ndarray):
        d["A_U3i"] = [float(v) for v in np.asarray(A3, float)]
        d["B_U3i"] = [float(v) for v in np.asarray(B3, float)]
        d["U3i_form"] = [0.0] * 6
        d["U3i_quad_Uref"] = [0.0] * 6
        d["U3i_quad_Talfa"] = [1.0] * 6
        d["U3i_quad_alfa"] = [0.0] * 6
    else:
        # paper1_config._QuadraticGasIonDU: U3i = lin_A*(T/Tc3) + lin_B
        # + mask * quad(Uref, Talfa, alfa).
        mask = np.asarray(A3._mask, float)
        d["A_U3i"] = [float(v) for v in np.asarray(A3._lin_A, float)]
        d["B_U3i"] = [float(v) for v in np.asarray(B3, float)]
        d["U3i_form"] = [float(m) for m in mask]
        d["U3i_quad_Uref"] = [float(A3._uref) if m else 0.0 for m in mask]
        d["U3i_quad_Talfa"] = [float(A3._talfa) if m else 1.0 for m in mask]
        d["U3i_quad_alfa"] = [float(A3._alfa) if m else 0.0 for m in mask]

    d["Uref_ii"] = [float(v) for v in
                    np.asarray(P.Uref_ii, float).flatten()]  # row-major
    # Wilson omegas (flash.py module constants: H2O 0.3443, CH4 w2,
    # CO2 0.22394).
    d["omega_wilson"] = [0.3443, float(P.w2), 0.22394]
    return d


def write_par(d, path, header):
    lines = [f"# {h}" for h in header]
    lines.append("# format: name = value [value ...]; ion order Na Cl K Ca Mg SO4;")
    lines.append("# Uref_ii: 36 values row-major.  Full repr precision "
                 "(round-trips to the exact float64).")
    for k, vals in d.items():
        lines.append(f"{k} = " + " ".join(repr(float(v)) for v in vals))
    Path(path).write_text("\n".join(lines) + "\n")
    print(f"wrote {path}  ({len(d)} parameters)")


def main():
    outdir = Path(sys.argv[1]) if len(sys.argv) > 1 else HERE.parent / "params"
    outdir.mkdir(parents=True, exist_ok=True)

    # 1) pristine defaults (Papers II/III)
    write_par(collect(), outdir / "paperII_III.par", [
        "eCPA multi-salt parameters: Papers II/III pristine library defaults",
        "generated by fortran/tools/gen_params.py from ms_ecpa.parameters",
    ])

    # 2) Paper I (apply, dump, restore)
    paper1_config.apply_paper1()
    try:
        write_par(collect(), outdir / "paper1.par", [
            "eCPA parameters: Paper-I (I&ECR 2026) CO2-H2O-NaCl configuration",
            "generated via ms_ecpa.paper1_config.apply_paper1()",
            "scope: z_CH4 = 0 and NaCl-only brines (mi = m,m,0,0,0,0)",
        ])
    finally:
        paper1_config.restore_paper1()


if __name__ == "__main__":
    main()
